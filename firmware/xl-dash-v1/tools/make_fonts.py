#!/usr/bin/env python3
"""Make fonts.h for the XL dash: anti-aliased (4-bit alpha) fonts from Inter.

Inter is by Rasmus Andersson, SIL Open Font License 1.1 (free to embed).
Run:  python3 make_fonts.py  [path/to/Inter/otf/folder]
Writes ../fonts.h next to the sketch.

Digits are forced to the same width (tabular) so numbers don't jiggle
sideways as they count.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fonts.h")
ASCII = "".join(chr(c) for c in range(32, 127))

# name, file, pixel size, characters (None = all printable ASCII)
FONTS = [
    ("F_SPEED", "Inter-Bold.otf", 124, "0123456789-"),
    ("F_GEAR", "Inter-Bold.otf", 86, "0123456789N-"),
    ("F_BIG", "Inter-Bold.otf", 36, "0123456789.-:% "),
    ("F_MED", "Inter-SemiBold.otf", 24, None),
    ("F_SMALL", "Inter-SemiBold.otf", 15, None),
]


def build(name, file, size, chars):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    ascent, descent = font.getmetrics()
    contiguous = chars is None
    chars = ASCII if contiguous else chars
    digit_adv = max(font.getlength(d) for d in "0123456789")
    glyphs, data = [], bytearray()
    for ch in chars:
        adv = font.getlength(ch)
        tab_shift = 0
        if ch.isdigit():
            tab_shift = (digit_adv - adv) / 2  # centre the digit in the tabular cell
            adv = digit_adv
        bbox = font.getbbox(ch, anchor="ls")  # relative to baseline-left
        if ch == " " or bbox[2] <= bbox[0]:
            glyphs.append((len(data), 0, 0, 0, 0, round(adv)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w + 4, h + 4), 0)
        ImageDraw.Draw(img).text((2 - x0 + tab_shift % 1, 2 - y0), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if not box:
            glyphs.append((len(data), 0, 0, 0, 0, round(adv)))
            continue
        img = img.crop(box)
        w, h = img.size
        xo = round(x0 - 2 + box[0] + int(tab_shift))
        yo = y0 - 2 + box[1]  # negative = above baseline
        px = list(img.getdata())
        off = len(data)
        for i in range(0, len(px), 2):
            a = (px[i] + 8) // 17
            b = (px[i + 1] + 8) // 17 if i + 1 < len(px) else 0
            data.append((min(a, 15) << 4) | min(b, 15))
        glyphs.append((off, w, h, xo, yo, round(adv)))
    return {
        "name": name, "data": data, "glyphs": glyphs, "chars": None if contiguous else chars,
        "ascent": ascent, "descent": descent, "size": size, "file": file,
    }


def emit(fonts):
    out = ["// Generated by tools/make_fonts.py from Inter (SIL OFL 1.1). Do not edit by hand.",
           "#pragma once", "#include <stdint.h>", "",
           "struct AAGlyph { uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; };",
           "struct AAFont { const uint8_t *bmp; const AAGlyph *g; const char *map; uint8_t first, count, ascent, descent; };",
           ""]
    total = 0
    for f in fonts:
        n = f["name"].lower()
        total += len(f["data"])
        out.append(f"// {f['name']}: {f['file']} {f['size']} px, {len(f['glyphs'])} glyphs, {len(f['data'])} bytes")
        out.append(f"static const uint8_t {n}_bmp[] = {{")
        d = f["data"]
        for i in range(0, len(d), 24):
            out.append("  " + ",".join(f"0x{b:02X}" for b in d[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const AAGlyph {n}_g[] = {{")
        for g in f["glyphs"]:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        mp = "nullptr" if f["chars"] is None else '"%s"' % f["chars"]
        out.append(f"static const AAFont {f['name']} = {{ {n}_bmp, {n}_g, {mp}, 32, {len(f['glyphs'])}, {f['ascent']}, {f['descent']} }};")
        out.append("")
    out.insert(2, f"// Total font data: {total} bytes (in flash)")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(OUT), total, "bytes")


if __name__ == "__main__":
    emit([build(*f) for f in FONTS])
